/** Product → the shape the bundle's add-to-bag call expects. */
function bridgeProduct(productId) {
  const product = productById(productId) || catalogProduct(productId);
  if (!product) return null;
  return { id: product.id, name: product.name, shortName: product.shortName || product.name, price: product.price };
}

/**
 * Seams installed into the bundle (see PATCHES in store/build-store.mjs):
 *
 *   __armoniaAddLive(product, color, size, quantity, openBag)
 *     Called at the top of the bundle's add-to-bag handler. We return true so
 *     the bundle's localStorage handler is skipped and the add goes to the
 *     server instead, then we write the result back into React state.
 *
 *   __armoniaBindBag(setItems, openModal)
 *     Called while the page component renders, which is the only place its
 *     setState callbacks are reachable. That is how the header counter, the
 *     bag drawer and the toasts stay in sync with the server's bag.
 */
/**
 * The bundle hands us its own full product object when something is added, and
 * a bare id everywhere else. Accept both, and register whatever we learn so bag
 * lines can render the right photograph and name.
 */
function resolveProduct(product) {
  if (!product) return null;
  if (typeof product === 'string') {
    const known = productById(product) || catalogProduct(product);
    if (known) return known;
    return { id: product, name: product, shortName: product, type: 'custom', images: {} };
  }
  if (product.id && !productById(product.id)) {
    state.products = [...state.products, product];
  }
  return product;
}

function installBagHooks(bridge) {
  let reactSetBag = null;
  let lastPushed = '[]';

  const pushToReact = () => {
    if (!reactSetBag) return;
    const raw = state.items.map((item) => ({
      key: `${item.productId}-${item.color}-${item.size}`,
      id: item.productId,
      color: item.color,
      size: item.size,
      quantity: item.quantity,
    }));
    // The hook runs during render, so never call setState synchronously and
    // never push the same list twice (that would loop forever).
    const signature = JSON.stringify(raw);
    if (signature === lastPushed) return;
    lastPushed = signature;
    setTimeout(() => {
      try {
        reactSetBag(raw);
      } catch (err) {
        console.warn('[store] could not sync the storefront bag', err);
      }
    }, 0);
  };

  state.listeners.add(pushToReact);

  window.__armoniaBindBag = (setItems, openModal) => {
    reactSetBag = typeof setItems === 'function' ? setItems : null;
    state.openModal = openModal;
    pushToReact();
    return true;
  };

  window.__armoniaAddLive = (product, color, size, quantity = 1, openBag = false) => {
    const resolved = resolveProduct(product);
    const productId = resolved && resolved.id;
    if (!productId) return false;
    (async () => {
      const before = new Set(state.items.map((item) => item.key));
      try {
        await addItem({ productId, color, size, quantity });
        const added = state.items.find((item) => !before.has(item.key));
        const name = (added && added.product && (added.product.shortName || added.product.name)) || resolved.shortName || resolved.name || 'Your good thing';
        if (openBag) openBagPanel();
        else toast(`${name} added to your bag.`, 'ok', { label: 'View bag', onClick: openBagPanel });
      } catch (err) {
        if (globalThis.__STORE_DEBUG) console.error('[store] add failed', err.stack);
        toast(err.message, 'error');
      }
    })();
    return true;
  };

  void bridge;
}

/** Open the bag drawer through the bundle's own state, not a DOM click. */
function openBagPanel() {
  if (typeof state.openModal === 'function') state.openModal({ type: 'cart' });
  else {
    const button = document.querySelector('.bag-button');
    if (button) button.click();
  }
}

function start(bridge) {
  state.config = bridge.config || window.__ARMONIA_CONFIG__ || {};
  state.products = Array.isArray(state.config.products) ? state.config.products : [];

  injectStyles();

  /* ── React shells: mount the vanilla panels inside the bundle's tree ── */
  const makeShell = (mountFn, getProps) => {
    const React = bridge.React;
    return function StoreLiveShell(props) {
      const ref = React.useRef(null);
      React.useEffect(() => {
        if (!ref.current) return undefined;
        const cleanup = mountFn(ref.current, getProps(props));
        return () => {
          if (typeof cleanup === 'function') cleanup();
        };
        // eslint-disable-next-line react-hooks/exhaustive-deps
      }, []);
      return bridge.jsx('div', { ref, className: 'store-live-root' });
    };
  };

  const BagShell = makeShell(mountBag, (props) => ({ onClose: props.onClose, onShop: props.onShop }));
  const InfoShell = makeShell(mountInfo, (props) => ({ type: props.type, onClose: props.onClose }));
  bridge.swap({ bag: BagShell, info: InfoShell });

  /* ── Route every "Add to bag" through the server ── */
  installBagHooks(bridge);

  wireNewsletter();

  /* ── Data ── */
  const params = new URLSearchParams(window.location.search);
  loadCatalog().then(() => {
    loadBag().then(() => {
      loadShipping();
      if (params.get('checkout') === 'success' && params.get('session_id')) showOrderConfirmation(params.get('session_id'));
      if (params.get('contact') === '1') {
        setTimeout(() => {
          const trigger = Array.from(document.querySelectorAll('button')).find((button) => /get in touch|contact/i.test(button.textContent || ''));
          if (trigger) trigger.click();
        }, 600);
      }
    });
  });

  // The store is live now — retire the "preview" chrome once React paints.
  const relabel = () => {
    let changed = false;
    document.querySelectorAll('.preview-label').forEach((node) => {
      if (node.dataset.live) return;
      node.dataset.live = '1';
      node.innerHTML = '<span></span> SECURE CHECKOUT';
      changed = true;
    });
    if (changed) syncHeaderCount();
  };
  setTimeout(relabel, 300);
  // Only react when storefront chrome is (re)rendered, and let React settle
  // first — the observer must never write to nodes it is watching.
  new MutationObserver((mutations) => {
    const relevant = mutations.some((mutation) =>
      Array.from(mutation.addedNodes).some(
        (node) => node.nodeType === 1 && (node.matches('.preview-label, .bag-count') || node.querySelector('.preview-label, .bag-count')),
      ),
    );
    if (relevant) requestAnimationFrame(relabel);
  }).observe(document.body, { childList: true, subtree: true });
}

