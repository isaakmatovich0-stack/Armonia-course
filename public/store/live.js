/* ============================================================================
   ARMONIA CONNECT — LIVE STORE RUNTIME
   ----------------------------------------------------------------------------
   The storefront bundle (store/frontend.bundle.js, generated by
   store/build-store.mjs from the Armonia Studio export) already contains the
   entire shopping experience: catalog, filters, search, favorites, product
   pages, gallery, toasts. What it does NOT contain is a real store — it was
   exported as a self-contained "preview" with a fake checkout.

   This file keeps everything the bundle does well and replaces only the parts
   that must be real:

     • the bag / cart panel      → live bag backed by /api/store/bag
     • the demo checkout form    → Stripe Checkout (redirect)
     • the info modal            → real policies + a working contact form
     • the newsletter form       → real subscribers (Resend)
     • the order success screen  → real order lookup by Stripe session id
     • "preview store" chrome    → removed

   How it plugs in: the bundle exposes a tiny bridge (window.ArmoniaBridge) at
   the end of its module scope — React itself, the jsx factory, and `swap()`,
   which reassigns the bundle's own `bg` (cart) and `Eg` (info modal) function
   bindings. Each React component below is a 6-line shell that mounts vanilla
   DOM into a ref'd div, so all interactive UI in this file is plain DOM: no
   JSX runtime, no extra dependencies, no second copy of React.

   Everything the store charges for is re-priced server-side from the same
   catalog (api/store/catalog.js) — the browser can never invent a price.
   ========================================================================== */

