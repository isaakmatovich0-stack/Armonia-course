function wireNewsletter() {
  // The bundle keeps its own submit handler (and writes to localStorage). We
  // intercept in the capture phase, stop the React handler, and post for real.
  document.addEventListener(
    'submit',
    async (event) => {
      const form = event.target;
      if (!form.classList || !form.classList.contains('newsletter-form')) return;
      event.preventDefault();
      event.stopPropagation();
      const input = form.querySelector('input[type=email]');
      const email = input && input.value.trim();
      if (!email) return;
      const button = form.querySelector('button[type=submit]');
      if (button) button.disabled = true;
      try {
        await api('/subscribe', { method: 'POST', body: JSON.stringify({ email, source: 'store-newsletter' }) });
        form.replaceWith(
          el(
            'div',
            { class: 'newsletter-success', role: 'status' },
            el('span', { class: 'store-success-check', html: ICON.check }),
            el('div', {}, el('strong', {}, 'You’re on the list.'), el('span', {}, 'New goods, fresh stories, a little good energy — straight to your inbox.')),
          ),
        );
      } catch (err) {
        toast(err.message, 'error');
        if (button) button.disabled = false;
      }
    },
    true,
  );
}

