/**
 * Pull live prices + stock caps from the server. The bundle's own config stays
 * the source for copy, colours and imagery; the server is the source for
 * money, so a stale page can never sell at an old price.
 */
async function loadCatalog() {
  // By now the storefront has rendered and published its own config.
  if (!state.products.length) {
    const config = (globalThis.__ARMONIA_CONFIG__ && globalThis.__ARMONIA_CONFIG__.products) || (state.config && state.config.products);
    if (Array.isArray(config)) state.products = config.slice();
  }
  try {
    const payload = await api('/catalog');
    (payload.products || []).forEach((product) => state.catalog.set(product.id, product));
    state.products = state.products.map((product) => {
      const live = state.catalog.get(product.id);
      return live && typeof live.priceCents === 'number' ? { ...product, price: live.priceCents / 100 } : product;
    });
    state.checkoutLive = payload.checkoutLive !== false;
    state.shipping = state.shipping || payload.shipping || null;
    // Keep the bundle's own price table in step with the server.
    if (globalThis.__ARMONIA_CONFIG__ && Array.isArray(globalThis.__ARMONIA_CONFIG__.products)) {
      state.products.forEach((product) => {
        const target = globalThis.__ARMONIA_CONFIG__.products.find((entry) => entry.id === product.id);
        if (target) target.price = product.price;
      });
    }
  } catch (err) {
    console.warn('[store] catalog unavailable, using the page’s own prices:', err.message);
  }
}

