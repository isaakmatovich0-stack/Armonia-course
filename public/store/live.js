/**
 * Bag id fallback. The server sets an HttpOnly cookie, but some browsers and
 * webviews block cookies entirely; the same id also rides along in a header,
 * kept in memory here and mirrored to localStorage when it is available.
 */
function cartHeader() {
  try {
    return window.localStorage.getItem('armonia-cart-id') || undefined;
  } catch {
    return undefined;
  }
}

function rememberCartId(response) {
  const id = response.headers && response.headers.get && response.headers.get('X-Cart-Id');
  if (!id) return;
  try {
    if (window.localStorage.getItem('armonia-cart-id') !== id) window.localStorage.setItem('armonia-cart-id', id);
  } catch {
    /* storage blocked — the cookie still covers this session */
  }
}

async function api(path, options = {}) {
  const headers = { ...(options.body ? { 'Content-Type': 'application/json' } : {}), ...(options.headers || {}) };
  if (path !== '/catalog' && path !== '/shipping') {
    const id = cartHeader();
    if (id) headers['X-Cart-Id'] = id;
  }
  const res = await fetch(`${API}${path}`, {
    credentials: 'same-origin',
    ...options,
    headers,
  });
  rememberCartId(res);
  let payload = null;
  try {
    payload = await res.json();
  } catch {
    payload = null;
  }
  if (!res.ok) {
    const error = new Error((payload && payload.error) || 'Something went wrong. Please try again.');
    error.status = res.status;
    error.payload = payload;
    throw error;
  }
  return payload || {};
}

/* ───────────────────────────── store state ───────────────────────────── */

const state = {
  config: {},
  products: [],
  catalog: new Map(),
  bag: null, // last bag payload from /api/store/bag
  items: [], // [{ key, productId, color, size, quantity }] — the UI's copy
  shipping: null,
  listeners: new Set(),
  checkoutLive: true,
  busy: false,
};

const catalogProduct = (id) => state.catalog.get(id) || null;
const productById = (id) => state.products.find((product) => product.id === id) || null;
const itemKey = (productId, color, size) => `${productId}|${color}|${size}`;

function notify() {
  state.listeners.forEach((fn) => {
    try {
      fn();
    } catch (err) {
      console.warn('[store] listener failed', err);
    }
  });
}

/** Recompute the display bag from the server payload + our item list. */
function setBag(payload) {
  state.bag = payload || null;
  const lines = (payload && (payload.lines || (payload.bag && payload.bag.lines))) || [];
  state.items = lines.map((line) => ({
    key: line.key,
    productId: line.productId,
    color: line.colorKey || line.color,
    size: line.size,
    quantity: line.quantity,
    line,
  }));
  syncHeaderCount();
  notify();
}

function bagLines() {
  return state.items.map((item) => ({ ...item, product: productById(item.productId) || {}, line: item.line }));
}

function bagTotals() {
  const bag = state.bag || {};
  const subtotal = bag.subtotalCents || 0;
  const discount = bag.discountCents || 0;
  const shipping = bag.shippingCents || 0;
  const threshold = bag.freeShippingThresholdCents || (state.shipping && state.shipping.freeShippingThresholdCents) || 7500;
  return {
    subtotal,
    discount,
    shipping,
    total: bag.totalCents != null ? bag.totalCents : Math.max(0, subtotal - discount + shipping),
    threshold,
    remaining: Math.max(0, threshold - subtotal),
    promo: bag.promo || null,
    count: bag.count || 0,
    freeShipping: shipping === 0 && (bag.lines || []).length > 0,
  };
}

function maxFor(productId, color) {
  const live = catalogProduct(productId);
  if (color === 'sky') return Math.min(10, (live && live.maxPerOrder) || 20);
  return (live && live.maxPerOrder) || 20;
}

function imageFor(product, colorKey) {
  if (!product || !product.type) return null;
  if (product.images && product.images[colorKey]) return product.images[colorKey];
  if (product.type === 'stickers' || product.type === 'custom') return null;
  if (product.type === 'windbreaker') return `/store/images/windbreaker-front-${colorKey}.webp`;
  return `/store/images/${product.type}-${colorKey}.webp`;
}

function colorName(colorKey) {
  const colors = (state.config && state.config.colors) || {};
  return (colors[colorKey] && colors[colorKey].name) || colorKey;
}

function colorHex(colorKey) {
  const colors = (state.config && state.config.colors) || {};
  return (colors[colorKey] && colors[colorKey].hex) || '#eeece4';
}

function syncHeaderCount() {
  const count = bagTotals().count;
  document.querySelectorAll('.bag-count').forEach((badge) => {
    // Never write an unchanged value: a MutationObserver watches the body for
    // new header chrome, and rewriting identical text would loop forever.
    if (badge.textContent !== String(count)) badge.textContent = String(count);
  });
  document.querySelectorAll('.bag-button').forEach((button) => {
    const label = `Open shopping bag (${count} items)`;
    if (button.getAttribute('aria-label') !== label) button.setAttribute('aria-label', label);
  });
}

function toast(message, kind = 'ok', action = null) {
  document.querySelectorAll('.store-live-toast').forEach((node) => node.remove());
  const node = el('div', { class: `store-live-toast ${kind}`, role: 'status' }, message);
  if (action && action.label) {
    node.appendChild(
      el(
        'button',
        {
          type: 'button',
          class: 'store-toast-action',
          onClick: () => {
            node.remove();
            action.onClick();
          },
        },
        action.label,
      ),
    );
  }
  document.body.appendChild(node);
  setTimeout(() => node.classList.add('leaving'), 4200);
  setTimeout(() => node.remove(), 5000);
}

/* ───────────────────────────── bag actions ───────────────────────────── */

/**
 * Optimistically apply a change to our local item list, then persist it and
 * accept whatever the server says. Optimism matters here: the storefront's
 * "Added to your bag" toast and header counter update instantly, and the panel
 * is correct by the time it opens.
 */
async function persist(action, mutateLocal) {
  const previous = state.items.slice();
  mutateLocal(state.items);
  syncHeaderCount();
  notify();
  try {
    const payload = await api('/bag', {
      method: 'POST',
      body: JSON.stringify({ action: action.action, key: action.key, productId: action.productId, color: action.color, size: action.size, quantity: action.quantity, code: action.code }),
    });
    setBag(payload);
    return payload;
  } catch (err) {
    state.items = previous;
    notify();
    throw err;
  }
}

function addItem({ productId, color, size, quantity = 1 }) {
  return persist(
    { action: 'add', productId, color, size, quantity },
    (items) => {
      const key = itemKey(productId, color, size);
      const existing = items.find((item) => item.key === key);
      const max = maxFor(productId, color);
      if (existing) existing.quantity = Math.min(max, existing.quantity + quantity);
      else items.push({ key, productId, color, size, quantity: Math.min(max, quantity), line: null });
    },
  );
}

function updateQuantity(key, quantity) {
  return persist({ action: 'update', key, quantity }, (items) => {
    const index = items.findIndex((item) => item.key === key);
    if (index === -1) return;
    if (quantity <= 0) items.splice(index, 1);
    else items[index].quantity = quantity;
  });
}

function removeItem(key) {
  return persist({ action: 'remove', key }, (items) => {
    const index = items.findIndex((item) => item.key === key);
    if (index !== -1) items.splice(index, 1);
  });
}

async function applyPromo(code) {
  const payload = await api('/bag', { method: 'POST', body: JSON.stringify({ action: 'promo', code }) });
  setBag(payload);
  return payload;
}

async function loadBag() {
  try {
    setBag(await api('/bag'));
  } catch (err) {
    console.warn('[store] bag load failed:', err.message);
  }
}

async function loadShipping() {
  if (state.shipping) return state.shipping;
  try {
    state.shipping = await api('/shipping');
    state.checkoutLive = state.shipping.live !== false;
  } catch {
    state.shipping = null;
  }
  return state.shipping;
}

/* ───────────────────────────── overlay shell ───────────────────────────── */

function overlay(panelClass, onClose, { labelledBy } = {}) {
  const panel = el('div', { class: `modal-panel ${panelClass}` });
  const close = el('button', { class: 'modal-close icon-button', 'aria-label': 'Close', onClick: onClose }, svg('close'));
  panel.appendChild(close);
  // `cart-modal` gets the bundle's drawer treatment (slides in from the right,
  // full height); everything else is a centred panel.
  const variant = /cart-modal/.test(panelClass) ? 'store-overlay drawer' : 'store-overlay';
  const root = el(
    'div',
    {
      class: variant,
      role: 'dialog',
      'aria-modal': 'true',
      'aria-labelledby': labelledBy || null,
      onClick: (event) => {
        if (event.target === root) onClose();
      },
    },
    panel,
  );
  const onKey = (event) => {
    if (event.key === 'Escape') onClose();
  };
  document.addEventListener('keydown', onKey);
  const previousOverflow = document.body.style.overflow;
  document.body.style.overflow = 'hidden';
  const cleanup = () => {
    document.removeEventListener('keydown', onKey);
    document.body.style.overflow = previousOverflow;
  };
  return { root, panel, cleanup };
}

